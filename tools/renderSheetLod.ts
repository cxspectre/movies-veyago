// renderSheetLod.ts — render the endless sheet's level-of-detail images (BIBLE4 §1.6) from the chapters:
//   public/tex/sheet/<chapterId>.png   each region, finished, transparent, 2x           (compositions SheetRegionAlpha-<id>)
//   public/tex/sheet/far-rough.png     the whole sheet at 1/8 scale with the glimpses   (SheetFarAlpha-rough)
//   public/tex/sheet/far-done.png      the whole sheet at 1/8 scale, finished regions   (SheetFarAlpha-done)
// usage: npx tsx tools/renderSheetLod.ts [chapterId|far-rough|far-done ...] [--gl=swangle|angle|...]
// Re-run it whenever a chapter changes. FILM_GL picks the GL renderer (cloud: swangle); FILM_BROWSER a browser executable.
import {bundle} from '@remotion/bundler';
import {openBrowser, renderStill, selectComposition} from '@remotion/renderer';
import {existsSync, mkdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import sharp, {type OverlayOptions} from 'sharp';
import path from 'node:path';
import {FAR_IMAGE_SCALE, IMAGE_CHAPTERS, REGION_IMAGE_SCALE, regionBounds} from '../src/endless/lod';
import {SHEET} from '../src/sheet4';
import {resolveGl} from './glFlag';

const OUT_DIR = path.resolve('public/tex/sheet');
const FAR = ['far-rough', 'far-done'] as const;
const MANIFEST = path.resolve('src/endless/lodManifest.ts');
const CROP_PAD = 8;
/** Longest side of a region PNG in pixels: a few huge images decoding at once failed in headless Chrome. The crop is in sheet px, so shrinking only lowers the sharpness. */
const MAX_SIDE = 4096;

type Crop = {x: number; y: number; w: number; h: number};

/** Trim a region PNG to its drawn pixels (a decoded 7200 x 4400 image is 126 MB; its content is a few hundred KB).
 * Returns the crop in region-local sheet px, or null for an empty image. */
const trimToContent = async (file: string, scale: number): Promise<Crop | null> => {
  const {data, info} = await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject: true});
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if ((data[(y * info.width + x) * 4 + 3] as number) === 0) continue;
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
  }
  if (x1 < 0) return null;
  const left = Math.max(0, x0 - CROP_PAD * scale);
  const top = Math.max(0, y0 - CROP_PAD * scale);
  const width = Math.min(info.width, x1 + CROP_PAD * scale) - left;
  const height = Math.min(info.height, y1 + CROP_PAD * scale) - top;
  const shrink = Math.min(1, MAX_SIDE / Math.max(width, height));
  let pipeline = sharp(file).extract({left, top, width, height});
  if (shrink < 1) pipeline = pipeline.resize(Math.round(width * shrink), Math.round(height * shrink), {kernel: 'lanczos3'});
  const cropped = await pipeline.png({compressionLevel: 9, effort: 10}).toBuffer();
  writeFileSync(file, cropped);
  return {x: left / scale, y: top / scale, w: width / scale, h: height / scale};
};

type Job = {composition: string; file: string; scale: number};

const jobsFor = (requested: readonly string[]): readonly Job[] => {
  const all: readonly Job[] = [
    ...IMAGE_CHAPTERS.map((id) => ({composition: `SheetRegionAlpha-${id}`, file: id, scale: REGION_IMAGE_SCALE})),
    ...FAR.map((name) => ({composition: `SheetFarAlpha-${name.slice('far-'.length)}`, file: name, scale: 1})),
  ];
  if (requested.length === 0) return all;
  const known = new Set(all.map((j) => j.file));
  const unknown = requested.filter((r) => !known.has(r));
  if (unknown.length > 0) throw new Error(`Unknown image(s): ${unknown.join(', ')}. Known: ${[...known].join(', ')}`);
  return all.filter((j) => requested.includes(j.file));
};

/** Merge the new crops into src/endless/lodManifest.ts (chapters not re-rendered keep their entry). */
const mergeManifest = (crops: Record<string, Crop>, empty: readonly string[]): void => {
  const old = existsSync(MANIFEST) ? [...readFileSync(MANIFEST, 'utf8').matchAll(/^\s+(\w+): (\{.*\}),$/gm)] : [];
  const merged: Record<string, Crop> = Object.fromEntries(old.map((m) => [m[1] as string, JSON.parse((m[2] as string).replace(/(\w+):/g, '"$1":')) as Crop]));
  Object.assign(merged, crops);
  for (const id of empty) delete merged[id];
  const rows = Object.entries(merged).map(([id, c]) => `  ${id}: {x: ${c.x}, y: ${c.y}, w: ${c.w}, h: ${c.h}},`);
  writeFileSync(MANIFEST, `// lodManifest.ts — GENERATED by tools/renderSheetLod.ts. Where each region PNG sits inside its region (sheet px, region-local).\n// The PNGs are trimmed to their drawn pixels so a finished region costs a few hundred KB to decode, not 126 MB.\nexport const REGION_IMAGE_CROP: Record<string, {x: number; y: number; w: number; h: number}> = {\n${rows.join('\n')}\n};\n`);
};

/** far-done.png: every region PNG (as just rendered) shrunk to 1/8 and placed on the sheet, so it always agrees with them. */
const composeFarDone = async (): Promise<void> => {
  const manifest = [...readFileSync(MANIFEST, 'utf8').matchAll(/^\s+(\w+): (\{.*\}),$/gm)];
  const crops = Object.fromEntries(manifest.map((m) => [m[1] as string, JSON.parse((m[2] as string).replace(/(\w+):/g, '"$1":')) as Crop]));
  const layers: OverlayOptions[] = [];
  for (const id of IMAGE_CHAPTERS) {
    const crop = crops[id];
    const file = path.join(OUT_DIR, `${id}.png`);
    if (!crop || !existsSync(file)) continue;
    const b = regionBounds(id);
    const w = Math.max(1, Math.round(crop.w * FAR_IMAGE_SCALE));
    const h = Math.max(1, Math.round(crop.h * FAR_IMAGE_SCALE));
    const input = await sharp(file).resize(w, h, {kernel: 'lanczos3'}).png().toBuffer();
    layers.push({input, left: Math.round((b.x0 + crop.x) * FAR_IMAGE_SCALE), top: Math.round((b.y0 + crop.y) * FAR_IMAGE_SCALE)});
  }
  const out = path.join(OUT_DIR, 'far-done.png');
  const width = SHEET.width * FAR_IMAGE_SCALE;
  const height = SHEET.height * FAR_IMAGE_SCALE;
  await sharp({create: {width, height, channels: 4, background: {r: 0, g: 0, b: 0, alpha: 0}}}).composite(layers).png({compressionLevel: 9, effort: 10}).toFile(out);
  console.log('lod', out, `${layers.length} regions`);
};

const main = async (): Promise<void> => {
  const args = process.argv.slice(2);
  const flags = args.filter((a) => a.startsWith('--'));
  const jobs = jobsFor(args.filter((a) => !a.startsWith('--')));
  mkdirSync(OUT_DIR, {recursive: true});
  const serveUrl = await bundle({entryPoint: path.resolve('src/index.ts')});
  const browser = await openBrowser('chrome', {browserExecutable: process.env.FILM_BROWSER ?? null, chromiumOptions: {gl: resolveGl(flags)}});
  const crops: Record<string, Crop> = {};
  const empty: string[] = [];
  for (const job of jobs) {
    if (job.file === 'far-done') continue;
    const composition = await selectComposition({serveUrl, id: job.composition, puppeteerInstance: browser});
    const output = path.join(OUT_DIR, `${job.file}.png`);
    const started = Date.now();
    await renderStill({composition, serveUrl, frame: 0, output, scale: job.scale, imageFormat: 'png', puppeteerInstance: browser});
    const crop = job.file.startsWith('far-') ? null : await trimToContent(output, job.scale);
    if (crop) crops[job.file] = crop;
    else if (!job.file.startsWith('far-')) {
      // Nothing drawn (the line's own region: the line itself is live): no image, so nothing is decoded or mounted for it.
      rmSync(output);
      empty.push(job.file);
    }
    console.log('lod', output, `${((Date.now() - started) / 1000).toFixed(1)}s`, crop ? JSON.stringify(crop) : '');
  }
  mergeManifest(crops, empty);
  if (jobs.some((j) => j.file === 'far-done')) await composeFarDone();
  await browser.close({silent: true});
};

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
