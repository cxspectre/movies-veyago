// makeTextures.fonts.ts — reads the bundled hand-lettering faces and writes their glyph metrics as TypeScript,
// so the handwriting layout (and the pencil position while writing) is pure and identical in every renderer.
import * as fontkit from 'fontkit';
import path from 'node:path';

export type FaceSource = {key: string; family: string; weight: number; file: string};

export const HAND_FACES: readonly FaceSource[] = [
  {key: 'caveat-500', family: 'Caveat', weight: 500, file: 'caveat-latin-500-normal.woff2'},
  {key: 'caveat-700', family: 'Caveat', weight: 700, file: 'caveat-latin-700-normal.woff2'},
  {key: 'kalam-400', family: 'Kalam', weight: 400, file: 'kalam-latin-400-normal.woff2'},
  {key: 'kalam-700', family: 'Kalam', weight: 700, file: 'kalam-latin-700-normal.woff2'},
  {key: 'patrick-400', family: 'Patrick Hand', weight: 400, file: 'patrick-hand-latin-400-normal.woff2'},
  {key: 'reenie-400', family: 'Reenie Beanie', weight: 400, file: 'reenie-beanie-latin-400-normal.woff2'},
];

const EXTRA_CODEPOINTS = [0x2018, 0x2019, 0x201c, 0x201d, 0x2013, 0x2014, 0x2026, 0x20ac];
const CODEPOINTS = [
  ...Array.from({length: 95}, (_, i) => 32 + i),
  ...Array.from({length: 96}, (_, i) => 160 + i),
  ...EXTRA_CODEPOINTS,
];

const r3 = (v: number): number => Math.round(v * 1000) / 1000;

type FontLike = {
  unitsPerEm: number;
  ascent: number;
  descent: number;
  xHeight: number;
  capHeight: number;
  hasGlyphForCodePoint: (cp: number) => boolean;
  glyphForCodePoint: (cp: number) => {advanceWidth: number; bbox: {minX: number; maxX: number; minY: number; maxY: number}};
};

const faceMetrics = (fontsDir: string, face: FaceSource): string => {
  const font = fontkit.openSync(path.join(fontsDir, face.file)) as unknown as FontLike;
  const em = font.unitsPerEm;
  const glyphs = CODEPOINTS.filter((cp) => font.hasGlyphForCodePoint(cp)).map((cp) => {
    const g = font.glyphForCodePoint(cp);
    const b = g.bbox;
    const empty = !Number.isFinite(b.minX) || b.maxX <= b.minX;
    // [advance, xMin, xMax, yMin, yMax] in em, y up.
    const m = empty ? [g.advanceWidth / em, 0, 0, 0, 0] : [g.advanceWidth / em, b.minX / em, b.maxX / em, b.minY / em, b.maxY / em];
    return `    ${JSON.stringify(String.fromCodePoint(cp))}: [${m.map(r3).join(', ')}],`;
  });
  return [
    `  '${face.key}': {`,
    `    family: '${face.family}', weight: ${face.weight},`,
    `    ascent: ${r3(font.ascent / em)}, descent: ${r3(font.descent / em)}, xHeight: ${r3(font.xHeight / em)}, capHeight: ${r3(font.capHeight / em)},`,
    `    glyphs: {`,
    ...glyphs.map((l) => `  ${l}`),
    `    },`,
    `  },`,
  ].join('\n');
};

export const fontMetricsSource = (fontsDir: string): string =>
  [
    '// handMetrics.ts — GENERATED by tools/makeTextures.ts from public/fonts. Do not edit by hand.',
    '// Glyph metrics in em units: [advance, xMin, xMax, yMin, yMax] (y up).',
    '',
    'export type GlyphMetric = readonly [number, number, number, number, number];',
    'export type FaceMetrics = {',
    '  family: string;',
    '  weight: number;',
    '  ascent: number;',
    '  descent: number;',
    '  xHeight: number;',
    '  capHeight: number;',
    '  glyphs: Readonly<Record<string, GlyphMetric>>;',
    '};',
    '',
    `export type HandFace = ${HAND_FACES.map((f) => `'${f.key}'`).join(' | ')};`,
    '',
    'export const HAND_METRICS: Record<HandFace, FaceMetrics> = {',
    ...HAND_FACES.map((f) => faceMetrics(fontsDir, f)),
    '};',
    '',
  ].join('\n');
